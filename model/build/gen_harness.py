"""Generate model/harness/src/Main.java from the same kernel.java + params.py used for the .alp.

Main.java mirrors what AnyLogic generates for the parts the kernel touches: parameters become
public fields, the class code is pasted verbatim, functions become methods, start-up code runs
initModel(). It compiles against the stub engine (to run) and against the real AnyLogic engine
jar (compile only, to check every API call the kernel makes).
"""
import os

from kernel_parse import parse_kernel, timetable_java
from params import PARAMS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "harness", "src")


def java_default(t, v):
    return v


def main():
    os.makedirs(OUT, exist_ok=True)
    classcode, funcs = parse_kernel()
    lines = ["import com.anylogic.engine.*;", "",
             "/** GENERATED by model/build/gen_harness.py - do not edit. Mirrors RakeFlow.alp Main. */",
             "public class Main extends Agent {"]
    lines.append("    // ---- parameters ----")
    for name, t, v, _ in PARAMS:
        lines.append(f"    public {t} {name} = {java_default(t, v)};")
    lines.append("    // ---- class code ----")
    lines.append(classcode)
    lines.append(timetable_java())
    lines.append("    // ---- functions ----")
    for f in funcs:
        ps = ", ".join(f"{t} {n}" for t, n in f["params"])
        lines.append(f"    /** {f['doc']} */")
        lines.append(f"    {f['ret']} {f['name']}({ps}) {{")
        lines.append(f["body"])
        lines.append("    }")
    lines.append("    // ---- start-up / destroy as in the .alp ----")
    lines.append("    public void startup() { initModel(); }")
    lines.append("    public void destroy() { writeResults(); }")
    lines.append("}")
    open(os.path.join(OUT, "Main.java"), "w").write("\n".join(lines) + "\n")
    print("wrote", os.path.join(OUT, "Main.java"), len(funcs), "functions")


if __name__ == "__main__":
    main()
